def build_manual_checks(level):
    """构建当前等保级别的人工核查项列表。
    二级 = 所有 "二级" 条目
    三级 = 所有 "二级" 条目 + 所有 "三级" 条目"""
    items = []
    for mod_dict, category, prefix in _MODULES:
        counter = 0
        # 基础项（二级三级都有）
        for name, clause, lv, expected, suggestion in mod_dict.get("二级", []):
            counter += 1
            items.append(CheckItem(
                item_id=f"{prefix}-{counter:03d}",
                name=name, category=category,
                level=lv, clause=clause,
                expected=expected, suggestion=suggestion,
                runner=None,
            ))
        # 仅三级的增强项
        if level == "三级":
            for name, clause, lv, expected, suggestion in mod_dict.get("三级", []):
                counter += 1
                items.append(CheckItem(
                    item_id=f"{prefix}-{counter:03d}",
                    name=name, category=category,
                    level=lv, clause=clause,
                    expected=expected, suggestion=suggestion,
                    runner=None,
                ))
    return items
